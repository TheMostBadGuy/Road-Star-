const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('C:/Users/Will/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
let browser;

(async () => {
  const guide = 'E:/TeslaRoadsterSim/Research/ROADSTER_LAYOUT.html';
  const output = path.dirname(__filename);
  const html = fs.readFileSync(guide, 'utf8');
  const references = [...html.matchAll(/(?:src|href|data-image)="([^"]+)"/g)].map(m => m[1]);
  const missing = references.filter(x => !/^(?:https?:|#|data:)/.test(x)).filter(x => !fs.existsSync(path.resolve(path.dirname(guide), x)));
  browser = await chromium.launch({ headless: true, executablePath: 'C:/Users/Will/AppData/Local/ms-playwright/chromium-1228/chrome-win64/chrome.exe', args: ['--disable-gpu'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1080 }, deviceScaleFactor: 1 });
  const errors = [];
  const network = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { if (/^https?:/.test(r.url())) network.push(r.url()); });
  await page.goto('file:///' + guide, { waitUntil: 'load' });
  await page.locator('img[src]').evaluateAll(async imgs => { await Promise.all(imgs.map(async i => { i.loading = 'eager'; try { await i.decode(); } catch {} })); });
  await page.screenshot({ path: path.join(output, 'guide_desktop_exterior.png'), fullPage: true });
  const brokenImages = await page.locator('img[src]').evaluateAll(imgs => imgs.filter(i => !i.complete || i.naturalWidth === 0).map(i => i.getAttribute('src')));
  await page.getByRole('tab', { name: /Layout/ }).click();
  await page.getByRole('button', { name: 'Top packaging' }).click();
  await page.getByRole('button', { name: 'Component 6 Rocket vessel' }).click();
  const component = await page.locator('#part-title').innerText();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: path.join(output, 'guide_desktop_layout.png'), fullPage: true });
  await page.getByRole('tab', { name: /Specification evidence/ }).click();
  await page.locator('#evidence-filter').selectOption('u');
  const unknownRows = await page.locator('#evidence-body tr').count();
  await page.getByRole('tab', { name: /Cockpit/ }).click();
  await page.getByRole('button', { name: 'Enlarge official track setup reference' }).click();
  const modalVisible = await page.locator('#image-modal').isVisible();
  await page.keyboard.press('Escape');
  const modalClosed = !(await page.locator('#image-modal').isVisible());
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: path.join(output, 'guide_desktop_cockpit.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('tab', { name: /Exterior/ }).click();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: path.join(output, 'guide_mobile_exterior.png'), fullPage: true });
  const mobileOverflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  const result = { missingLocalFiles: missing, brokenImages, pageErrors: errors, externalRequests: network, clickedComponent: component, unknownRows, imageModalOpened: modalVisible, imageModalClosedWithEscape: modalClosed, mobilePageOverflow: mobileOverflow };
  fs.writeFileSync(path.join(output, 'guide_verification.json'), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result, null, 2));
  await browser.close();
  if (missing.length || brokenImages.length || errors.length || network.length || !modalVisible || !modalClosed || unknownRows !== 5 || mobileOverflow) process.exitCode = 1;
})().catch(async e => { console.error(e); if (browser) await browser.close(); process.exitCode = 1; });
