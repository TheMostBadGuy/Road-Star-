"""Generate Unreal/RoadsterSim/Source/RoadsterSim/Public/SuspensionRig.h from Blender/export/suspension_rig.json.

Plain Python (no bpy). Everything is converted to the Unreal frame here (cm, +Y = car's right), so the pawn only
interpolates tables and composes rotations:
  position (x, y, z) m        -> (x, -y, z) * 100 cm
  hinge axis a, angle t       -> axis (ax, -ay, az), angle -t   (the header stores the converted axis; the runtime negates t)
  quaternion (w, x, y, z)     -> FQuat(-x, y, -z, w)
Run:  python -I gen_suspension_header.py [rig.json] [out.h]
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
RIG = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "export", "suspension_rig.json")
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "..", "..", "Unreal", "RoadsterSim", "Source", "RoadsterSim", "Public", "SuspensionRig.h")

JOINTS = {"hinge": "Hinge", "rigid": "Rigid", "aim": "Aim", "aim_scale": "AimScale", "aim+scale": "AimScale", "aim+spin": "AimSpin", "static": "Static"}
ANGLES = {"lower_arm_deg": 0, "upper_arm_deg": 1, "rocker_deg": 2}


def P(v):
    return (v[0] * 100.0, -v[1] * 100.0, v[2] * 100.0)


def D(v):
    return (v[0], -v[1], v[2])


def Q(q):
    w, x, y, z = q
    return (-x, y, -z, w)          # FQuat order X, Y, Z, W


def f3(v):
    return "{ %.5ff, %.5ff, %.5ff }" % tuple(v)


def f4(v):
    return "{ %.7ff, %.7ff, %.7ff, %.7ff }" % tuple(v)


def main():
    rig = json.load(open(RIG))
    corners = ["FL", "FR", "RL", "RR"]
    # moving point tables present in every corner (3-vectors per travel sample)
    point_keys = []
    for c in corners:
        for k, v in rig["corners"][c]["travel_table"].items():
            if isinstance(v, list) and v and isinstance(v[0], list) and len(v[0]) == 3 and k != "wheel_centre" and k not in point_keys:
                point_keys.append(k)
    n_travel = len(rig["corners"]["FL"]["travel_table"]["travel_m"])
    n_steer = max(len(rig["corners"][c]["steer_table"]["steer_deg"]) for c in corners if "steer_table" in rig["corners"][c])

    L = ["// GENERATED by Blender/scripts/gen_suspension_header.py from export/suspension_rig.json - do not edit.",
         "// Unreal frame: centimetres, +X forward, +Y = car's RIGHT, +Z up, relative to the body origin.",
         "#pragma once", "", "namespace SuspensionRig", "{",
         "\tenum EJoint : int { Hinge, Rigid, Aim, AimScale, AimSpin, Static };",
         "\tconstexpr int NumTravel = %d;" % n_travel,
         "\tconstexpr int NumSteer = %d;" % n_steer,
         "\tconstexpr int NumPoints = %d;" % len(point_keys)]
    for i, k in enumerate(point_keys):
        L.append("\tconstexpr int Pt_%s = %d;" % (k, i))
    L += ["",
          "\tstruct FCornerTables",
          "\t{",
          "\t\tbool bFront;",
          "\t\tfloat TravelCm[NumTravel];",
          "\t\tfloat AngleDeg[3][NumTravel];            // lower arm, upper arm, rocker (Blender sign; negate about the stored axes)",
          "\t\tfloat WheelCentre[NumTravel][3];",
          "\t\tfloat UprightQuat[NumTravel][4];          // X, Y, Z, W (Unreal)",
          "\t\tfloat Points[NumPoints][NumTravel][3];",
          "\t\tfloat SpringScale[NumTravel];",
          "\t\tint SteerCount;",
          "\t\tfloat SteerDeg[NumSteer];                 // road-wheel angle, Blender sign (+ = nose left)",
          "\t\tfloat RackYCm[NumSteer];                  // rack shift along Unreal Y",
          "\t\tfloat KingpinDeg[NumSteer];",
          "\t\tfloat SteerTO[NumSteer][3];               // track-rod outer point at static travel",
          "\t};", "",
          "\tstruct FPart",
          "\t{",
          "\t\tconst char* Name;",
          "\t\tint Corner;        // 0 FL, 1 FR, 2 RL, 3 RR, -1 body",
          "\t\tint Joint;",
          "\t\tfloat Pivot[3];",
          "\t\tfloat Axis[3];     // hinge axis (Unreal) - rotate by -AngleDeg",
          "\t\tfloat StaticDir[3];",
          "\t\tint AngleTable;    // hinge: 0 lower arm, 1 upper arm, 2 rocker",
          "\t\tint PivotPoint;    // aim: pivot follows this table point (-1 = fixed pivot)",
          "\t\tint TargetPoint;   // aim: target table point (-1 = TargetFixed)",
          "\t\tfloat TargetFixed[3];",
          "\t\tbool bRack;        // pivot moves with the steering rack",
          "\t\tbool bFollowDamper;// spring: pivot rides on the damper body",
          "\t};", ""]

    L.append("\tstatic const FCornerTables Corners[4] = {")
    for c in corners:
        cr = rig["corners"][c]
        tt = cr["travel_table"]
        st = cr.get("steer_table")
        L.append("\t\t{ // %s" % c)
        L.append("\t\t\t%s," % ("true" if c[0] == "F" else "false"))
        L.append("\t\t\t{ %s }," % ", ".join("%.3ff" % (t * 100) for t in tt["travel_m"]))
        L.append("\t\t\t{ " + ", ".join("{ %s }" % ", ".join("%.4ff" % a for a in tt[k]) for k in ("lower_arm_deg", "upper_arm_deg", "rocker_deg")) + " },")
        L.append("\t\t\t{ " + ", ".join(f3(P(v)) for v in tt["wheel_centre"]) + " },")
        L.append("\t\t\t{ " + ", ".join(f4(Q(q)) for q in tt["upright_quat"]) + " },")
        pts = []
        for k in point_keys:
            vals = tt.get(k)
            if vals is None:
                vals = [[0, 0, 0]] * n_travel
            pts.append("{ " + ", ".join(f3(P(v)) for v in vals) + " }")
        L.append("\t\t\t{ " + ", ".join(pts) + " },")
        L.append("\t\t\t{ %s }," % ", ".join("%.5ff" % s for s in tt["spring_scale"]))
        if st:
            n = len(st["steer_deg"])
            pad = lambda arr, z: list(arr) + [z] * (n_steer - len(arr))
            L.append("\t\t\t%d," % n)
            L.append("\t\t\t{ %s }," % ", ".join("%.4ff" % a for a in pad(st["steer_deg"], 0.0)))
            L.append("\t\t\t{ %s }," % ", ".join("%.4ff" % (-r * 100) for r in pad(st["rack_m"], 0.0)))
            L.append("\t\t\t{ %s }," % ", ".join("%.4ff" % a for a in pad(st["kingpin_deg"], 0.0)))
            L.append("\t\t\t{ " + ", ".join(f3(P(v)) for v in pad(st["TO"], [0, 0, 0])) + " },")
        else:
            L.append("\t\t\t0, {}, {}, {}, {},")
        L.append("\t\t},")
    L.append("\t};")
    L.append("")

    parts = []
    for ci, c in enumerate(corners):
        for p in rig["corners"][c]["parts"]:
            parts.append((ci, p))
    for name in rig.get("static_parts", []):
        if not any(p["name"] == name for _, p in parts):
            parts.append((-1, {"name": name, "pivot": [0, 0, 0], "joint": "static"}))
    L.append("\tstatic const FPart Parts[] = {")
    for ci, p in parts:
        joint = JOINTS[p["joint"]]
        axis = D(p.get("axis", [1, 0, 0]))
        sdir = D(p.get("static_dir", [1, 0, 0]))
        angle = ANGLES.get(p.get("table", ""), -1)
        def point_of(s):
            m = re.search(r"table\.(\w+)", s or "")
            return point_keys.index(m.group(1)) if m and m.group(1) in point_keys else -1
        pivot_pt = point_of(p.get("pivot_follows"))
        target_pt = point_of(p.get("target"))
        fixed = (0.0, 0.0, 0.0)
        m = re.search(r"\[([-\d.eE]+),\s*([-\d.eE]+),\s*([-\d.eE]+)\]", p.get("target") or "")
        if m and target_pt < 0:
            fixed = P([float(m.group(i)) for i in (1, 2, 3)])
        rack = "rack" in (p.get("pivot_follows") or "")
        follow_damper = "damper" in (p.get("pivot_follows") or "").lower() and pivot_pt < 0
        L.append('\t\t{ "%s", %d, %s, %s, %s, %s, %d, %d, %d, %s, %s, %s },' % (
            p["name"], ci, joint, f3(P(p["pivot"])), f3(axis), f3(sdir), angle, pivot_pt, target_pt, f3(fixed),
            "true" if rack else "false", "true" if follow_damper else "false"))
    L.append("\t};")
    L.append("\tconstexpr int NumParts = %d;" % len(parts))
    L.append("}")
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(L) + "\n")
    print("wrote", OUT, "parts", len(parts), "points", point_keys)


if __name__ == "__main__":
    main()
